def run(command, **kwargs):
    try:
        subprocess.run(command, check=True, **kwargs)
    except subprocess.CalledProcessError as exc:
        raise AssertionError(
            "command failed with exit status %d: %s" % (
                exc.returncode, " ".join(map(str, command[:2])))) from None


def write_runtime_check(directory, name, source):
    """Write a runtime check without placing its source on the command line."""
    path = directory / name
    path.write_text(source, encoding="utf8")
    return path


def verify_source_boundary(generated, required=None):
    source = generated.read_text(encoding="utf8")
    forbidden = (
        "#include <Python.h>",
        "PyObject *",
        "PyThreadState *",
        "struct PyMethodDef",
        "struct PyModuleDef",
        "PyLong_FromLong(",
        "Py_INCREF",
        "Py_DECREF",
        "static HPyGlobal",
        "HPyGlobal_Store",
        "HPyGlobal_Load",
        "static HPy __pyx_hpy_const_",
        "static HPy __pyx_hpy_default_",
        "HPyMember_OBJECT",
    )
    found = [name for name in forbidden if name in source]
    if re.search(r"\bPy_buffer\b", source):
        found.append("Py_buffer")
    if found:
        raise AssertionError(
            "forbidden source-boundary spellings found: %s" %
            ", ".join(found))
    if required is None:
        required = (
            "#include <hpy.h>",
            "HPyDef_METH",
            "HPyFunc_O",
            "HPyLong_FromLongLong",
            "HPyFloat_FromDouble",
            "HPy_Dup",
            "HPyUnicode_FromString",
            "HPyUnicode_FromEncodedObject",
            "HPyBytes_FromStringAndSize",
            "ctx->h_LongType",
            "ctx->h_ComplexType",
            "ctx->h_ListType",
            "ctx->h_TupleType",
            "ctx->h_UnicodeType",
            "HPy_Type(",
            "HPyListBuilder_New",
            "HPyListBuilder_Cancel",
            "HPyTupleBuilder_New",
            "HPyTupleBuilder_Cancel",
            "HPyDict_New",
            "HPy_SetItem",
            "HPy_GetItem",
            "HPy_GetAttr_s",
            'HPy_SetAttr_s(ctx, m, "__pyx_hpy_const_',
            'HPy_SetAttr_s(ctx, m, "__pyx_hpy_default_',
            "HPy_Call",
            "HPy_CallTupleDict",
            "HPyArg_ParseKeywords",
            "HPyTracker_Close",
            "HPyDef_SLOT",
            "HPy_mod_exec",
            "HPyImport_ImportModule",
            "HPy_MODINIT",
        )
    missing = [name for name in required if name not in source]
    if missing:
        raise AssertionError("required HPy spellings missing: %s" % ", ".join(missing))


def _forbidden_binary_imports(symbol_output):
    forbidden = set(re.findall(
        r"\b_*Py(?:[A-Z_]|Exc_)[A-Za-z0-9_]*\b", symbol_output))
    forbidden.update(re.findall(
        r"\bpython\d+(?:_d)?\.dll\b", symbol_output, re.IGNORECASE))
    return sorted(forbidden)


def _undefined_symbol_command(binary):
    if os.name == "nt":
        dumpbin = shutil.which("dumpbin")
        if dumpbin:
            return [dumpbin, "/nologo", "/imports", str(binary)]
        llvm_nm = shutil.which("llvm-nm")
        if llvm_nm:
            return [llvm_nm, "--undefined-only", str(binary)]
        objdump = shutil.which("objdump")
        if objdump:
            return [objdump, "-p", str(binary)]
        raise AssertionError(
            "cannot audit Universal binary imports: install dumpbin, "
            "llvm-nm, or objdump")

    nm = shutil.which("nm") or shutil.which("llvm-nm")
    if not nm:
        raise AssertionError(
            "cannot audit Universal binary imports: install nm or llvm-nm")
    return [nm, "-u", str(binary)]


def verify_binary_boundary(binary):
    result = subprocess.run(
        _undefined_symbol_command(binary),
        check=True,
        capture_output=True,
        text=True,
    )
    forbidden = _forbidden_binary_imports(result.stdout + result.stderr)
    if forbidden:
        raise AssertionError(
            "Universal binary imports CPython symbols: %s" %
            ", ".join(forbidden))


